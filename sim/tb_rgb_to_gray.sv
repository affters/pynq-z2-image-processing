`timescale 1ns/1ps

module tb_rgb_to_gray;
    localparam integer MAX_VECTORS = 65536;

    reg         clk = 1'b0;
    reg         rst = 1'b1;
    reg  [23:0] in_rgb = 24'd0;
    reg         in_valid = 1'b0;
    wire        in_ready;
    wire [7:0]  out_gray;
    wire        out_valid;
    reg         out_ready = 1'b0;

    reg [23:0] input_rgb [0:MAX_VECTORS-1];
    reg [7:0] expected_gray [0:MAX_VECTORS-1];
    reg [7:0] directed_expected [0:31];
    integer vector_count;
    integer count_file;
    integer output_file;
    integer scan_result;
    integer accepted_count = 0;
    integer produced_count = 0;
    integer main_cycle = 0;
    integer timeout_cycles;
    reg main_phase = 1'b0;
    reg input_stalled = 1'b0;
    reg [23:0] held_input;
    reg output_stalled = 1'b0;
    reg [7:0] held_output;
    reg next_valid;
    reg [23:0] next_rgb;
    reg next_ready;

    rgb_to_gray dut (
        .clk(clk), .rst(rst),
        .in_rgb(in_rgb), .in_valid(in_valid), .in_ready(in_ready),
        .out_gray(out_gray), .out_valid(out_valid), .out_ready(out_ready)
    );

    always #5 clk = ~clk;

    // Used only for the short directed tests. Main vectors are checked
    // against expected_gray.hex, independently generated by Python.
    function automatic [7:0] directed_gray(input [23:0] rgb);
        reg [31:0] total;
        begin
            total = 77 * rgb[23:16] + 150 * rgb[15:8]
                  + 29 * rgb[7:0] + 128;
            directed_gray = total >> 8;
        end
    endfunction

    // All stimulus changes on the falling edge. Handshakes and the
    // scoreboard use values immediately before the following rising edge.
    task automatic step(
        input bit reset_value,
        input bit valid_value,
        input [23:0] rgb_value,
        input bit ready_value
    );
        reg stalled_at_edge;
        reg [7:0] gray_at_edge;
        reg [7:0] expected_value;
        begin
            @(negedge clk);
            rst = reset_value;
            in_valid = valid_value;
            in_rgb = rgb_value;
            out_ready = ready_value;
            #1;
            if (rst && in_ready !== 1'b0)
                $fatal(1, "in_ready must be low during reset");

            @(posedge clk);
            stalled_at_edge = out_valid && !out_ready;
            gray_at_edge = out_gray;
            if (rst) begin
                accepted_count = 0;
                produced_count = 0;
                input_stalled = 1'b0;
                output_stalled = 1'b0;
            end else begin
                if (in_ready !== 1'b0 && in_ready !== 1'b1)
                    $fatal(1, "in_ready contains X/Z");
                if (out_valid !== 1'b0 && out_valid !== 1'b1)
                    $fatal(1, "out_valid contains X/Z");
                if (input_stalled &&
                    (in_valid !== 1'b1 || in_rgb !== held_input))
                    $fatal(1, "testbench changed a stalled input");
                if (output_stalled &&
                    (out_valid !== 1'b1 || out_gray !== held_output))
                    $fatal(1, "output changed before a stalled value was consumed");

                // Check even unconsumed outputs. An output cannot precede
                // its input handshake in this registered, one-stage design.
                if (out_valid) begin
                    if (produced_count >= accepted_count)
                        $fatal(1, "unexpected or duplicated output at index %0d", produced_count);
                    if (main_phase)
                        expected_value = expected_gray[produced_count];
                    else
                        expected_value = directed_expected[produced_count];
                    if (out_gray !== expected_value)
                        $fatal(1, "gray mismatch phase=%0d index=%0d got=%02x expected=%02x",
                               main_phase, produced_count, out_gray, expected_value);
                end

                if (out_valid && out_ready) begin
                    if (main_phase)
                        $fdisplay(output_file, "%02x", out_gray);
                    produced_count = produced_count + 1;
                end

                if (in_valid && in_ready) begin
                    if (main_phase) begin
                        if (accepted_count >= vector_count)
                            $fatal(1, "accepted an input beyond the vector count");
                        if (in_rgb !== input_rgb[accepted_count])
                            $fatal(1, "input order mismatch at index %0d", accepted_count);
                    end else begin
                        if (accepted_count >= 32)
                            $fatal(1, "directed scoreboard overflow");
                        directed_expected[accepted_count] = directed_gray(in_rgb);
                    end
                    accepted_count = accepted_count + 1;
                end
                if (accepted_count - produced_count < 0 ||
                    accepted_count - produced_count > 1)
                    $fatal(1, "one-stage capacity violated: sent=%0d received=%0d",
                           accepted_count, produced_count);

                input_stalled = in_valid && !in_ready;
                held_input = in_rgb;
                output_stalled = stalled_at_edge;
                held_output = gray_at_edge;
            end

            // Also check immediately after nonblocking register updates.
            #1;
            if (rst) begin
                if (out_valid !== 1'b0 || in_ready !== 1'b0)
                    $fatal(1, "reset did not clear valid and block input");
            end else if (stalled_at_edge) begin
                if (out_valid !== 1'b1 || out_gray !== gray_at_edge)
                    $fatal(1, "output register changed under backpressure");
            end
        end
    endtask

    initial begin
        count_file = $fopen("count.txt", "r");
        if (count_file == 0)
            $fatal(1, "cannot open count.txt in the simulation working directory");
        scan_result = $fscanf(count_file, "%d", vector_count);
        $fclose(count_file);
        if (scan_result != 1 || vector_count < 1 || vector_count > MAX_VECTORS)
            $fatal(1, "count.txt must contain a count from 1 to %0d", MAX_VECTORS);
        $readmemh("input_rgb.hex", input_rgb, 0, vector_count - 1);
        $readmemh("expected_gray.hex", expected_gray, 0, vector_count - 1);
        output_file = $fopen("rtl_gray.hex", "w");
        if (output_file == 0)
            $fatal(1, "cannot create rtl_gray.hex");

        // Directed streaming checks: consecutive handshakes, a bubble,
        // full-register backpressure, then simultaneous consume/refill.
        step(1, 0, 24'd0, 0);
        step(1, 0, 24'd0, 0);
        step(0, 1, 24'h000000, 1);
        step(0, 1, 24'hffffff, 1);
        step(0, 0, 24'd0, 1);
        step(0, 1, 24'hff0000, 0);
        step(0, 1, 24'h00ff00, 0);
        step(0, 1, 24'h00ff00, 0);
        step(0, 1, 24'h00ff00, 1);
        step(0, 0, 24'd0, 1);
        step(0, 0, 24'd0, 1);
        if (accepted_count != 4 || produced_count != 4)
            $fatal(1, "directed streaming test lost a handshake");

        // Leave a valid output pending, offer another blocked input, and
        // reset while out_ready is high. Neither item may emerge later.
        step(0, 1, 24'h123456, 0);
        step(0, 1, 24'hfedcba, 0);
        step(1, 1, 24'hfedcba, 1);
        step(0, 0, 24'd0, 1);
        step(0, 0, 24'd0, 1);
        if (accepted_count != 0 || produced_count != 0 || out_valid !== 1'b0)
            $fatal(1, "reset did not discard pending work");

        main_phase = 1'b1;
        timeout_cycles = vector_count * 20 + 256;
        while (produced_count < vector_count) begin
            if (main_cycle >= timeout_cycles)
                $fatal(1, "timeout: sent=%0d received=%0d expected=%0d",
                       accepted_count, produced_count, vector_count);

            // Start at full throughput, then add long stalls and bubbles.
            if (main_cycle < 16)
                next_ready = 1'b1;
            else if (main_cycle < 24)
                next_ready = 1'b0;
            else
                next_ready = (main_cycle % 17 >= 6);

            if (input_stalled) begin
                next_valid = 1'b1;
                next_rgb = held_input;
            end else if (accepted_count < vector_count) begin
                next_valid = (main_cycle < 24) ||
                             (main_cycle % 11 < 3) || (main_cycle % 11 > 5);
                next_rgb = input_rgb[accepted_count];
            end else begin
                next_valid = 1'b0;
                next_rgb = 24'd0;
            end
            step(0, next_valid, next_rgb, next_ready);
            main_cycle = main_cycle + 1;
        end

        if (accepted_count != vector_count || produced_count != vector_count)
            $fatal(1, "main vector count mismatch");
        // A duplicated trailing value must also be detected.
        step(0, 0, 24'd0, 1);
        step(0, 0, 24'd0, 1);
        step(0, 0, 24'd0, 1);
        $fclose(output_file);
        $display("SIM_PASS rgb_to_gray count=%0d", vector_count);
        $finish;
    end

    // Independent watchdog also covers a hung directed test.
    initial begin
        repeat (MAX_VECTORS * 20 + 1024) @(posedge clk);
        $fatal(1, "global simulation timeout");
    end
endmodule
